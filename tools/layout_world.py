def place_infill(layout, sectors, limit=None, tries=4000):
    """Buildings at random spots, facing the nearest road, until `limit` fit or the tries run out."""
    rng = layout.rng
    for sector, weights in sectors.items():
        region, gap, _ = SECTORS[sector]
        placed = 0
        for _ in range(tries):
            if limit is not None and placed >= limit:
                break
            x, y = rng.uniform(region[0], region[2]), rng.uniform(region[1], region[3])
            i = int(np.argmin(distances(layout.road_xy, x, y)))
            heading = float(layout.road_heading[i])
            rx, ry = layout.road_xy[i]
            left = -math.sin(heading) * (x - rx) + math.cos(heading) * (y - ry) > 0
            yaw = (heading if left else heading + math.pi) + rng.gauss(0, math.radians(5))
            kind = layout.pick(weights, "infill")
            if in_region(layout.building_box(kind, x, y, yaw), region) and \
                    layout.place_building(f"{sector}_building", kind, x, y, yaw, gap):
                placed += 1


def place_poles(layout, roads):
    rng, count = layout.rng, 0
    for road in roads.values():
        if road.surface != "asphalt":
            continue
        s = rng.uniform(5, 15)
        while s < road.s[-1]:
            (px, py), heading, normal, half = road.at(s)
            s += rng.uniform(26, 36)
            x, y = px + normal[0] * (half + 0.9), py + normal[1] * (half + 0.9)
            if not (-200 <= x <= 200 and -125 <= y <= 104) or math.hypot(x, y + 110) < 20:   # clear of the pad
                continue
            box = Box(x, y, heading, *LANDMARK_HALF_EXTENTS_M["aero_sense_electric_pole"])
            if distances(layout.victim_xy, x, y).min() < 3.0 or any(box.overlaps(o) for o in layout.obstacles):
                continue
            quake = x < 0 and 0 < y < 100
            lean = (rng.uniform(-0.22, 0.22), rng.uniform(-0.22, 0.22)) if quake and rng.random() < 0.35 else (0.0, 0.0)
            count += 1
            layout.add(f"pole_{count}", "aero_sense_electric_pole", x, y, heading, box, *lean)


def write_strips(roads, valley):
    by_surface = {}
    for road in roads.values():
        by_surface.setdefault(road.surface, []).append(road)
    for surface, (filename, header, z0, dz) in SURFACES.items():
        lines = [f"# {header} (world coordinates), generated by tools/layout_world.py: one strip per",
                 "# road along its curve, its width wandering; UVs tile every 8 m.", "vn 0 0 1"]
        base = 1
        for k, road in enumerate(by_surface.get(surface, [])):
            z = z0 + k * dz
            normal = np.stack((-np.sin(road.heading), np.cos(road.heading)), axis=1)
            for side in (-1, 1):
                edge = road.xy + side * normal * road.half_width[:, None]
                ground = z + valley.height(edge)               # tracks run over the bank and down into the valley
                for (x, y), s, h, height in zip(edge, road.s, road.half_width, ground):
                    lines += [f"v {x:.2f} {y:.2f} {height:.4f}", f"vt {side * h / 8:.3f} {s / 8:.3f}"]
            n = len(road.s)
            for j in range(n - 1):
                r0, r1, l0, l1 = base + j, base + j + 1, base + n + j, base + n + j + 1
                lines += [f"f {r0}/{r0}/1 {r1}/{r1}/1 {l1}/{l1}/1", f"f {r0}/{r0}/1 {l1}/{l1}/1 {l0}/{l0}/1"]
            base += 2 * n
        (MODELS / "aero_sense_roads" / "meshes" / filename).write_text("\n".join(lines) + "\n")


def blob(lines, base, cx, cy, radius, z, rng, k=40):
    phases = [rng.uniform(0, 6.3) for _ in range(3)]
    lines += [f"v {cx:.2f} {cy:.2f} {z:.4f}", f"vt {cx / 6:.3f} {cy / 6:.3f}"]
    for i in range(k):
        t = 2 * math.pi * i / k
        r = radius * (1 + 0.22 * math.sin(2 * t + phases[0]) + 0.12 * math.sin(5 * t + phases[1])
                      + 0.06 * math.sin(11 * t + phases[2]))
        x, y = cx + r * math.cos(t), cy + r * math.sin(t)
        lines += [f"v {x:.2f} {y:.2f} {z:.4f}", f"vt {x / 6:.3f} {y / 6:.3f}"]
    for i in range(k):
        a, b = base + 1 + i, base + 1 + (i + 1) % k
        lines.append(f"f {base}/{base}/1 {a}/{a}/1 {b}/{b}/1")
    return base + k + 1


def write_dust(layout, landmark_patches, rng):
    centres = [(x, y, r * 1.15) for x, y, r in layout.collapses if x < 0] + landmark_patches
    lines = ["# Concrete dust around S1's collapses (world coordinates), generated by tools/layout_world.py:",
             "# ragged blobs, each 0.6 mm above the last so none z-fight; galis start at 8 mm.", "vn 0 0 1"]
    base = 1
    for i, (x, y, r) in enumerate(centres[:10]):
        base = blob(lines, base, x, y, r * rng.uniform(0.9, 1.2), 0.002 + 0.0006 * i, rng)
    (MODELS / "aero_sense_ground" / "meshes" / "dust.obj").write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seed", type=int, default=26)
    args = parser.parse_args()
    rng = random.Random(args.seed)
    victims = yaml.safe_load(VICTIMS.read_text())["victims"]
    text = WORLD.read_text()
    start, stop = text.index(BEGIN), text.index(END)
    head = text[:start] + text[start:].split("\n", 1)[0] + "\n"
    landmarks, landmark_patches = [], []
    for include in ET.fromstring(text[:start] + text[stop:]).iter("include"):
        uri = (include.findtext("uri") or "")[len("model://"):]
        if uri in LANDMARK_HALF_EXTENTS_M:
            x, y, yaw = include_pose(include)
            landmarks.append(Box(x, y, yaw, *LANDMARK_HALF_EXTENTS_M[uri]))
            if uri.startswith("collapsed_"):
                landmark_patches.append((x, y, max(LANDMARK_HALF_EXTENTS_M[uri]) * 1.3))
    roads = {name: Road(name, surface, width, points, rng) for name, surface, width, points in ROADS}
    for name, road in roads.items():
        for box in landmarks:
            if box.contains(road.xy, road.half_width).any():
                print(f"note: {name} brushes the landmark at ({box.x:.0f}, {box.y:.0f})")
    valley = flood_valley.Valley(random.Random(args.seed))    # its own stream: layout changes leave the shore be
    valley.check(victims)
    layout = Layout(rng, victims, landmarks, list(roads.values()), valley)
    place_pinned(layout, victims)
    place_perched(layout, victims)
    place_vehicles(layout, roads)
    place_cordons(layout, roads)
    for sector, kinds, count, tries in ANCHORS:
        place_infill(layout, {sector: dict.fromkeys(kinds, 1.0)}, limit=count, tries=tries)
    place_frontage(layout, roads)
    place_infill(layout, {sector: weights for sector, (_, _, weights) in SECTORS.items()})
    place_poles(layout, roads)
    buildings = [line for line in layout.includes if BUILDING in line]
    print(f"{len(buildings)} buildings ({sum('collapsed' in b for b in buildings)} collapsed, "
          f"{sum('damaged' in b for b in buildings)} damaged), "
          f"{sum('electric_pole' in line for line in layout.includes)} poles")
    WORLD.write_text(head + "\n".join(layout.includes) + "\n    " + text[stop:])
    write_strips(roads, valley)
    write_dust(layout, landmark_patches, rng)
    flood_valley.write_meshes(MODELS, valley, rng)


if __name__ == "__main__":
    main()
