class Road:
    def __init__(self, name, surface, width, points, rng):
        self.name, self.surface = name, surface
        self.xy, self.s = catmull_rom(points)
        d = np.gradient(self.xy, axis=0)
        self.heading = np.arctan2(d[:, 1], d[:, 0])
        a, b = rng.uniform(0, 6.3), rng.uniform(0, 6.3)
        self.half_width = width / 2 * (1 + 0.07 * np.sin(self.s / 19 + a) + 0.04 * np.sin(self.s / 6.3 + b))

    def frontage(self, s, length, side):
        """Where a plot of this frontage starting at arc length `s` sits on one side of a curving road:
        (midpoint, heading of the chord, outward normal, distance from the chord to the road's edge)."""
        i0, i1 = np.searchsorted(self.s, (s, s + length)).clip(0, len(self.s) - 1)
        a, b = self.xy[i0], self.xy[i1]
        heading = math.atan2(b[1] - a[1], b[0] - a[0])
        normal = side * np.array((-math.sin(heading), math.cos(heading)))
        edge = float(((self.xy[i0:i1 + 1] - a) @ normal + self.half_width[i0:i1 + 1]).max())
        return (a + b) / 2, heading, normal, edge

    def at(self, s):
        i = int(np.clip(np.searchsorted(self.s, s), 0, len(self.s) - 1))
        normal = np.array((-math.sin(self.heading[i]), math.cos(self.heading[i])))
        return self.xy[i], float(self.heading[i]), normal, float(self.half_width[i])


def catmull_rom(points, step=1.0):
    p = [np.array(q, dtype=float) for q in points]
    p = [2 * p[0] - p[1]] + p + [2 * p[-1] - p[-2]]
    out = []
    for i in range(1, len(p) - 2):
        p0, p1, p2, p3 = p[i - 1], p[i], p[i + 1], p[i + 2]
        n = max(2, int(math.ceil(np.linalg.norm(p2 - p1) / step)))
        for t in np.arange(n) / n:
            out.append(0.5 * (2 * p1 + (p2 - p0) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t * t
                              + (3 * p1 - p0 - 3 * p2 + p3) * t ** 3))
    out.append(p[-2])
    xy = np.array(out)
    return xy, np.concatenate(([0.0], np.cumsum(np.linalg.norm(np.diff(xy, axis=0), axis=1))))


def rotate(yaw, x, y):
    return x * math.cos(yaw) - y * math.sin(yaw), x * math.sin(yaw) + y * math.cos(yaw)


class Box:
    """An oriented footprint: centre, heading and half extents."""

    def __init__(self, x, y, yaw, hx, hy):
        self.x, self.y, self.yaw, self.hx, self.hy = x, y, yaw, hx, hy

    def corners(self, grow=0.0):
        return [(self.x + dx, self.y + dy) for dx, dy in
                (rotate(self.yaw, sx * (self.hx + grow), sy * (self.hy + grow))
                 for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1)))]

    def contains(self, points, grow=0.0):
        """Mask of which (N, 2) points fall inside this box grown by `grow` (scalar or per point)."""
        dx, dy = points[:, 0] - self.x, points[:, 1] - self.y
        c, s = math.cos(self.yaw), math.sin(self.yaw)
        return (np.abs(dx * c + dy * s) < self.hx + grow) & (np.abs(-dx * s + dy * c) < self.hy + grow)

    def overlaps(self, other, gap=0.0):
        reach = math.hypot(self.hx, self.hy) + math.hypot(other.hx, other.hy) + 2 * gap
        if math.hypot(self.x - other.x, self.y - other.y) > reach:
            return False
        a, b = self.corners(gap), other.corners()
        for poly in (a, b):
            for i in range(4):
                (x1, y1), (x2, y2) = poly[i], poly[(i + 1) % 4]
                nx, ny = y2 - y1, x1 - x2
                pa, pb = [nx * x + ny * y for x, y in a], [nx * x + ny * y for x, y in b]
                if max(pa) < min(pb) or max(pb) < min(pa):
                    return False
        return True


class Layout:
    def __init__(self, rng, victims, landmarks, roads, valley):
        self.rng, self.valley = rng, valley
        self.victim_xy = np.array([(v["x"], v["y"]) for v in victims])
        self.obstacles = list(landmarks)
        self.road_xy = np.concatenate([r.xy for r in roads])
        self.road_heading = np.concatenate([r.heading for r in roads])
        self.road_half = np.concatenate([r.half_width for r in roads])
        self.includes, self.collapses = [], []
        self.building_count = 0
        self.footprints = {p.name[len(BUILDING):]: model_footprint(p / "model.sdf")
                           for p in MODELS.glob(BUILDING + "*")}

    def clear(self, box, gap, pinned_victim=None, rubble_m=0.0, on_road=False):
        """Whether a footprint fits. Rubble (the outer `rubble_m` of a damaged building's footprint)
        may spill onto a road or into the neighbour's rubble; it may never cover a casualty. Only a
        collapse pinned round a casualty in the street may stand `on_road`."""
        body = self.body(box, rubble_m)
        if not on_road and body.contains(self.road_xy, self.road_half + ROAD_SETBACK_M).any():
            return False
        near = box.contains(self.victim_xy, VICTIM_CLEARANCE_M)
        if pinned_victim is not None:
            near[pinned_victim] = False
        return not near.any() and not any(body.overlaps(o, gap) for o in self.obstacles)

    @staticmethod
    def body(box, rubble_m):
        return Box(box.x, box.y, box.yaw, max(0.5, box.hx - rubble_m), max(0.5, box.hy - rubble_m))

    def add(self, name, uri, x, y, yaw, box, roll=0.0, pitch=0.0):
        self.obstacles.append(box)
        z = self.valley.height_at(x, y)                    # on the terrain: down in the valley, up on its bank
        self.includes.append(f"    <include><name>{name}</name><pose>{x:.2f} {y:.2f} {z:.2f} {roll:.3f} {pitch:.3f} "
                             f"{yaw:.3f}</pose><uri>model://{uri}</uri></include>")

    def building_box(self, kind, x, y, yaw):
        cx, cy, hx, hy, _ = self.footprints[kind]
        dx, dy = rotate(yaw, cx, cy)
        return Box(x + dx, y + dy, yaw, hx, hy)

    def place_building(self, name, kind, x, y, yaw, gap, pinned_victim=None, on_road=None):
        """Place it if it fits; `name` is a prefix numbered in placing order unless pinned."""
        box = self.building_box(kind, x, y, yaw)
        rubble_m = 0.0 if kind.startswith(("house", "rowhouse", "apartment")) else RUBBLE_SPREAD_M
        on_road = pinned_victim is not None if on_road is None else on_road
        if not self.clear(box, gap, pinned_victim, rubble_m, on_road):
            return False
        if pinned_victim is None:
            self.building_count += 1
            name = f"{name}_{self.building_count}"
        self.add(name, BUILDING + kind, x, y, yaw, self.body(box, rubble_m))
        if not kind.startswith(("house", "rowhouse", "apartment")):
            self.collapses.append((box.x, box.y, max(box.hx, box.hy)))
        return True

    def pick(self, weights, surface):
        """A building kind; shops cluster on the asphalt roads and thin out in the galis."""
        kinds = list(weights)
        shop_scale = {"asphalt": 3.0, "lane": 0.2, "track": 0.2}.get(surface, 1.0)
        return self.rng.choices(kinds, [weights[k] * (shop_scale if k.endswith("_shop") else 1.0) for k in kinds])[0]


def in_region(box, region):
    x0, y0, x1, y1 = region
    return all(x0 <= x <= x1 and y0 <= y <= y1 for x, y in box.corners())


def distances(points, x, y):
    return np.hypot(points[:, 0] - x, points[:, 1] - y)


def place_pinned(layout, victims):
    by_id = {v["id"]: i for i, v in enumerate(victims)}
    for vid, kind, yaw_deg in PINNED:
        i, yaw = by_id[vid], math.radians(yaw_deg)
        dx, dy = rotate(yaw, CRACK_OFFSET_M, 0.0)
        x, y = victims[i]["x"] - dx, victims[i]["y"] - dy
        if not layout.place_building(f"s1_trapped_{vid.lower()}", kind, x, y, yaw, 0.3, pinned_victim=i):
            raise SystemExit(f"{vid}: its collapse overlaps a landmark or another casualty")


def intact_size(kind):
    """(width, depth, floors) of an intact make_buildings kind."""
    return next((w, d, floors) for name, w, d, floors, _, _ in make_buildings.INTACT if name == kind)


def perch_spot(kind: str, perch: str, person: dict) -> tuple:
    """Where someone on a perch stands: the (x, y) offset in the perch model's frame and the floor
    height above its base. `person` is their mesh's people.yaml entry. Also used by
    ml/make_dataset.py, so the dataset's perched people stand exactly as the scenario's do."""
    if perch == "car_roof":
        return (0.0, 0.0), HATCHBACK_ROOF_M
    w, d, floors = intact_size(kind)
    if perch == "terrace":
        return (0.0, -d / 2 + TERRACE_FROM_FRONT_M), make_buildings.PLINTH_M + floors * make_buildings.FLOOR_M + 0.02
    head_x, _, head_z = person["points"]["head"]
    inside = max(0.1, head_x - HEAD_OUT_OF_WINDOW_M)
    step_up = max(0.0, HEAD_IN_WINDOW_M - head_z)
    return (make_buildings.openings(w)[0], -d / 2 + inside), make_buildings.PLINTH_M + make_buildings.FLOOR_M + step_up


def place_perched(layout, victims):
    """Build what each flood casualty waits on, and check they stand on it: their z must be the
    terrain under it plus its roof or floor height, so nobody floats or stands in the water."""
    by_id = {v["id"]: i for i, v in enumerate(victims)}
    people = yaml.safe_load((VICTIMS.parent / "people.yaml").read_text())
    wrong = []
    for vid, kind in PERCHED:
        i = by_id[vid]
        v = victims[i]
        facing = math.radians(v.get("yaw_deg", 0.0))
        offset, height = perch_spot(kind, v["perch"], people[f"{v['character']}_{v['pose']}"])
        if v["perch"] == "car_roof":
            yaw = facing - math.pi / 2                                  # the models run along their y
            hx, hy = LANDMARK_HALF_EXTENTS_M[kind]
            layout.add(f"s2_stranded_{vid.lower()}", kind, v["x"], v["y"], yaw, Box(v["x"], v["y"], yaw, hx, hy))
            floor = layout.valley.height_at(v["x"], v["y"]) + height
        else:
            yaw = facing + math.pi / 2                                  # the front, model -y, faces where they look
            dx, dy = rotate(yaw, *offset)
            x, y = v["x"] - dx, v["y"] - dy
            if not layout.place_building(f"s2_refuge_{vid.lower()}", kind, x, y, yaw, 0.3, pinned_victim=i, on_road=False):
                raise SystemExit(f"{vid}: its {kind} overlaps a road, a landmark or another casualty; move it in victims.yaml")
            floor = layout.valley.height_at(x, y) + height
        if abs(floor - float(v.get("z", 0.0))) > 0.02:
            wrong.append(f"{vid} z: {floor:.2f}")
    if wrong:
        raise SystemExit("perched casualties must stand on their perch; set in victims.yaml: " + ", ".join(wrong))


def place_vehicles(layout, roads):
    rng = layout.rng
    for name, uri, road_name in VEHICLES:
        road, region = roads[road_name], SECTORS[name[:2]][0]
        hx, hy = LANDMARK_HALF_EXTENTS_M[uri]
        for _ in range(400):
            (px, py), heading, normal, half = road.at(rng.uniform(5, road.s[-1] - 5))
            if not (region[0] <= px <= region[2] and region[1] <= py <= region[3]):
                continue
            side = rng.choice((-1, 1)) * (half * 0.4 if road.surface == "asphalt" else 0.0)
            x, y = px + normal[0] * side, py + normal[1] * side
            skew = rng.gauss(0, math.radians(12 if name.startswith("s1") else 4))
            yaw = heading - math.pi / 2 + rng.choice((0, math.pi)) + skew     # the models run along their y
            box = Box(x, y, yaw, hx, hy)
            if distances(layout.victim_xy, x, y).min() >= VEHICLE_CLEARANCE_M and \
                    not any(box.overlaps(o, 0.5) for o in layout.obstacles):
                layout.add(name, uri, x, y, yaw, box)
                break
        else:
            print(f"warning: no room for {name} on {road_name}")


def place_cordons(layout, roads):
    for road_name, from_end in CORDONS:
        road = roads[road_name]
        (px, py), heading, normal, half = road.at(from_end if from_end > 0 else road.s[-1] + from_end)
        for k, side in enumerate((-0.55, 0.55)):
            x, y = px + normal[0] * side * half, py + normal[1] * side * half
            yaw = heading + math.pi / 2
            layout.add(f"cordon_{road_name}_{k + 1}", "jersey_barrier", x, y, yaw,
                       Box(x, y, yaw, *LANDMARK_HALF_EXTENTS_M["jersey_barrier"]))


def place_frontage(layout, roads):
    """Buildings along both sides of every street, fronts to the road, the odd plot left empty."""
    rng = layout.rng
    for road in roads.values():
        for side in (1, -1):
            s = rng.uniform(0, 6)
            while s < road.s[-1]:
                (px, py), *_ = road.at(s)
                sector = "s1" if px < 0 else "s2"
                region, gap, weights = SECTORS[sector]
                if rng.random() < 0.07:
                    s += rng.uniform(8, 15)
                    continue
                placed = None
                for _ in range(3):                    # a smaller building may fit where the first did not
                    kind = layout.pick(weights, road.surface)
                    cx, cy, hx, hy, _ = layout.footprints[kind]
                    (px, py), heading, normal, edge = road.frontage(s, 2 * hx, side)
                    yaw = (heading if side == 1 else heading + math.pi) + \
                        rng.gauss(0, math.radians(5 if kind.startswith("collapsed") else 1.5))
                    setback = rng.uniform(0.6, 2.4) if road.surface == "asphalt" else rng.uniform(0.5, 1.2)
                    fx, fy = px + normal[0] * (edge + setback + hy), py + normal[1] * (edge + setback + hy)
                    dx, dy = rotate(yaw, cx, cy)
                    x, y = fx - dx, fy - dy
                    if in_region(layout.building_box(kind, x, y, yaw), region) and \
                            layout.place_building(f"{sector}_building", kind, x, y, yaw, gap):
                        placed = hx
                        break
                if placed is not None:
                    s += 2 * placed + (rng.uniform(0.25, 0.6) if placed < 4 else rng.uniform(0.4, 2.2))
                else:
                    s += 1.5


